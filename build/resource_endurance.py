#!/usr/bin/env python3
"""Real owned-process endurance: verified Range churn and resource convergence.

Uses original generated bytes, private state and loopback ports. An eight-hour
run is recorded as such only after eight hours actually elapsed. This measures
server resources and byte correctness, not a decoder or Android playback.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import datetime
import hashlib
import json
import os
from pathlib import Path
import statistics
import time

from controlled_peer import LocalSwarm, PeerPlan
from playback_harness import OwnedServer, range_read, upload, MIB


def convergence(samples):
    if len(samples) < 12:
        return {'known': False, 'reason': 'insufficient_samples'}
    count = min(120, max(6, len(samples)//8))
    early, late = samples[6:6+count], samples[-count:]
    result = {'known': True, 'windows': count, 'metrics': {}, 'passed': True}
    for key, availability, allowance in [('rss_bytes','rss_available',128*MIB),('handles','handles_available',64),('goroutines',None,32)]:
        if availability and not all(row['memory'].get(availability) for row in early+late):
            result['known'] = False
            result['metrics'][key] = {'known':False}
            continue
        first = statistics.median(row['memory'][key] for row in early)
        last = statistics.median(row['memory'][key] for row in late)
        passed = last-first <= allowance
        result['metrics'][key] = {'known':True,'early_median':first,'late_median':last,'growth':last-first,'allowed_growth':allowance,'passed':passed}
        result['passed'] &= passed
    return result


def run(args):
    args.output.mkdir(parents=True, exist_ok=False)
    paths = []
    for index in range(2):
        path = args.output/f'original-generated-{index}.ts'
        block = bytes((value+index)%256 for value in range(256))*4096
        with path.open('wb') as output:
            for _ in range(48): output.write(block)
        paths.append(path)
    started = time.monotonic()
    report = {'schema_version':1,'started_at':datetime.datetime.now(datetime.timezone.utc).isoformat(),
              'executable_sha256':hashlib.sha256(args.executable.read_bytes()).hexdigest(),
              'requested_hours':args.hours,'synthetic_server_byte_test':True,'pid':os.getpid(),
              'cycles':0,'samples':[],'passed':False,'eight_hour_acceptance':False}
    server = OwnedServer(args.executable,args.output/'state',extra_settings={
        'CacheSize':64*MIB,'UseDisk':args.disk,'TorrentsSavePath':str((args.output/'rolling-cache').resolve()) if args.disk else '',
        'Flow':{'SwarmProfile':'adaptive','WarmSessionTimeoutSec':30,'GlobalCacheBudgetMB':64,'WarmCacheBudgetMB':16,'DiagnosticHistory':False}})
    def record():
        elapsed = time.monotonic()-started
        report['elapsed_seconds'] = elapsed
        (args.output/'report.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    try:
        server.ready()
        report['server_pid'] = server.process.pid
        with LocalSwarm(paths,peers=[PeerPlan(rate=16*MIB,request_queue=512)],piece_length=MIB,high_throughput=True) as swarm:
            torrent = upload(server,swarm)
            info_hash = swarm.info_hash.hex()
            files = torrent['file_stats']
            offsets = [0,paths[0].stat().st_size]
            deadline = started+args.hours*3600
            with ThreadPoolExecutor(max_workers=2) as workers:
                while time.monotonic() < deadline:
                    if server.process.poll() is not None: raise RuntimeError('Owned server exited during endurance')
                    tasks = []
                    for index, file in enumerate(files):
                        source = swarm.data[offsets[index]:offsets[index]+file['length']]
                        start = (report['cycles']*7*MIB)%max(1,len(source)-2*MIB)
                        tasks.append(workers.submit(range_read,server,info_hash,file['id'],source,start,start+MIB-1,report['cycles']%7==0))
                    for task in tasks: task.result(timeout=90)
                    runtime = server.json('/runtime/status')
                    report['samples'].append({'elapsed_seconds':time.monotonic()-started,'memory':runtime['memory'],
                        'allocation':runtime.get('cache_allocation'),'resources':runtime.get('resources')})
                    report['cycles'] += 1
                    if len(report['samples']) > 4000: report['samples'] = report['samples'][::2]
                    record()
                    time.sleep(min(args.interval,max(0,deadline-time.monotonic())))
            with server.request('/torrents',{'action':'drop','hash':info_hash}): pass
            settle = time.monotonic()+45
            while time.monotonic() < settle:
                runtime = server.json('/runtime/status')
                allocation = runtime.get('cache_allocation')
                if allocation is not None and allocation['active_readers']==0 and allocation['protected_bytes']==0:
                    report['released_allocation'] = allocation
                    break
                time.sleep(1)
            if 'released_allocation' not in report: raise AssertionError('Reader/reservation release did not converge')
            report['convergence'] = convergence(report['samples'])
            if report['convergence']['known'] and not report['convergence']['passed']: raise AssertionError('Resource growth exceeded the declared convergence allowance')
            if args.hours >= 8 and not report['convergence']['known']: raise AssertionError('Eight-hour acceptance requires known resource convergence')
            report['swarm'] = swarm.status()
            report['passed'] = True
            report['eight_hour_acceptance'] = args.hours >= 8 and time.monotonic()-started >= 8*3600 and report['convergence']['known']
    except Exception as error:
        report['failure_type'] = type(error).__name__
        report['failure'] = str(error)
        raise
    finally:
        server.close()
        record()
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--executable',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--hours',type=float,default=8)
    parser.add_argument('--interval',type=float,default=15)
    parser.add_argument('--disk',action='store_true')
    args = parser.parse_args()
    if not .01 <= args.hours <= 24 or not 1 <= args.interval <= 60: parser.error('hours .01..24 and interval 1..60 required')
    print(json.dumps({key:value for key,value in run(args).items() if key != 'samples'},indent=2))
