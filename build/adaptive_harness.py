#!/usr/bin/env python3
"""Isolated native acceptance for settings, capabilities and network policy.

Uses generated bytes, an owned loopback swarm and disposable state only.
Does not validate Android decoding or physical VPN/DNS leak protection.
"""
import argparse
import copy
import http.client
import json
import socket
import time
import urllib.error
from pathlib import Path

from controlled_peer import LocalSwarm
from maintenance_harness import expect_status
from playback_harness import MIB, OwnedServer, upload
from preparation_harness import restart_after_crash, wait_job


def state(server):
    return server.json('/settings', {'action': 'state'})


def apply(server, configuration, when='now', revision=None):
    current = state(server)
    with server.request('/settings', {'action': 'set', 'sets': configuration,
                                     'revision': revision or current['revision'],
                                     'when': when}, timeout=45):
        pass


def anonymous_range(server, path, source, start, end, method='GET'):
    with server.request(path, headers={'Authorization': '', 'Range': f'bytes={start}-{end}'}, method=method) as response:
        if response.status != 206 or response.headers['Content-Range'] != f'bytes {start}-{end}/{len(source)}':
            raise AssertionError('Capability Range semantics changed')
        if response.read() != (source[start:end+1] if method == 'GET' else b''):
            raise AssertionError('Capability returned wrong bytes')


def wait_effective(server, expected):
    deadline = time.monotonic()+45
    while time.monotonic() < deadline:
        try:
            current = state(server)
        except urllib.error.HTTPError as error:
            if error.code != 503:
                raise
            time.sleep(.25)
            continue
        if current.get('error'):
            raise AssertionError(current['error'])
        if not current.get('pending') and current.get('effective') == expected:
            return current
        time.sleep(.25)
    raise TimeoutError('Queued configuration did not become effective')


def run(executable, output):
    output.mkdir(parents=True, exist_ok=False)
    payload = output/'owned-episode.bin'
    source = bytes(range(256))*(16*MIB//256)
    payload.write_bytes(source)
    report = {'scope': 'generated native HTTP fixtures; no phone or physical VPN validation'}
    server = OwnedServer(executable, output/'state', auth=True)
    try:
        server.ready()
        initial = state(server)
        started = server.json('/flow/network')['started_at']
        configuration = copy.deepcopy(initial['saved'])
        configuration['CacheSize'] = 64*MIB
        configuration['Flow'].update(GlobalCacheBudgetMB=128, WarmCacheBudgetMB=16)
        plan = server.json('/settings', {'action': 'plan', 'sets': configuration})
        if plan['restart_required']:
            raise AssertionError('Cache policy incorrectly requires restart')
        apply(server, configuration, revision=initial['revision'])
        if server.json('/flow/network')['started_at'] != started:
            raise AssertionError('Hot settings restarted engine')
        expect_status(server, '/settings', 409, {'action': 'set', 'sets': initial['saved'], 'revision': initial['revision']})
        report['hot_apply_and_conflict'] = True
        configuration = state(server)['saved']
        configuration['Flow']['RequirePlaybackToken'] = True
        apply(server, configuration)
        with LocalSwarm([payload], rate=4*MIB) as swarm:
            item = upload(server, swarm)
            info_hash, index = item['hash'], item['file_stats'][0]['id']
            claim = {'hash': info_hash, 'index': index}
            expect_status(server, '/flow/playback-link', 401, claim, {'Authorization': ''})
            expect_status(server, '/flow/playback-link', 409, {**claim, 'index': index+10})
            capability = server.json('/flow/playback-link', claim)['path']
            anonymous_range(server, capability, source, 0, 65535)
            anonymous_range(server, capability, source, len(source)-65536, len(source)-1)
            anonymous_range(server, capability, source, MIB, MIB+65535, 'HEAD')
            expect_status(server, capability+'x', 401, headers={'Authorization': ''})
            expect_status(server, f'/play/{info_hash}/{index}', 401, headers={'Authorization': ''})
            expect_status(server, f'/stream?link={info_hash}&index={index}&stat=ffprobe', 401, headers={'Authorization': ''})
            expect_status(server, '/settings', 401, {'action': 'get'}, {'Authorization': ''})
            report['capability_scope_head_range_and_strong_policy'] = True

            # A tiny receive window retains a real HTTP reader while settings
            # are queued; no fake active-work marker participates.
            player = http.client.HTTPConnection('127.0.0.1', server.port, timeout=30)
            try:
                player.connect(); player.sock.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 4096)
                player.request('GET', capability, headers={'Range': f'bytes=0-{len(source)-1}'})
                response = player.getresponse()
                if response.status != 206 or response.read(1) != source[:1]:
                    raise AssertionError('Owned busy playback failed')
                next_config = copy.deepcopy(state(server)['saved'])
                next_config['ConnectionsLimit'] += 1
                plan = server.json('/settings', {'action': 'plan', 'sets': next_config})
                if not plan['restart_required'] or not plan['active_work']:
                    raise AssertionError('Real playback was not recognized')
                apply(server, next_config, 'idle')
                queued = state(server)
                if not queued.get('pending') or queued['effective']['ConnectionsLimit'] == next_config['ConnectionsLimit']:
                    raise AssertionError('Scheduled setting interrupted playback')
                time.sleep(2.5)
                if not state(server).get('pending'):
                    raise AssertionError('Idle worker ignored active reader')
                with server.request('/settings', {'action': 'cancel_pending', 'revision': state(server)['revision']}):
                    pass
                if state(server).get('pending'):
                    raise AssertionError('Cancellation left pending intent')
                apply(server, next_config, 'idle')
                restart_after_crash(server)
            finally:
                player.close()
                if 'response' in locals(): response.close()
            wait_effective(server, next_config)
            expect_status(server, capability, 401, headers={'Authorization': ''})
            report['idle_queue_cancel_and_crash_recovery'] = True

            # Retain real verified data, then enforce an unavailable adapter.
            request = {'hash': info_hash, 'file_index': index, 'action': 'start'}
            server.json('/flow/preparation', request)
            wait_job(server, 'ready')
            configuration = state(server)['saved']
            configuration['Flow'].update(TorrentInterface='Flow-missing-fixture-04917', RequireTorrentInterface=True)
            apply(server, configuration)
            wait_job(server, 'ready')
            exposure = server.json('/runtime/status')['exposure']
            binding = exposure['torrent_interface']
            if binding['state'] != 'WAIT_INTERFACE' or binding['dns_verified'] or binding['leak_protection_verified']:
                raise AssertionError('Unavailable adapter incorrectly reported protection')
            capability = server.json('/flow/playback-link', claim)['path']
            anonymous_range(server, capability, source, MIB, MIB+65535)
            report['unavailable_binding_preserves_verified_local_playback'] = True
            configuration['Flow'].update(TorrentInterface='', RequireTorrentInterface=False)
            apply(server, configuration)

        configuration = state(server)['saved']
        configuration['Flow'].update(SecurityProfile='restricted', ManagementOrigins='https://controller.example')
        apply(server, configuration)
        expect_status(server, '/settings', 403, {'action': 'get'}, {'Origin': 'https://foreign.example'})
        expect_status(server, '/settings', 200, {'action': 'get'}, {'Origin': 'https://controller.example'})
        limited = OwnedServer(executable, output/'rate-policy', auth=True,
                              extra_settings={'Flow': {'ManagementRateLimit': 2}})
        try:
            limited.ready() # first management request consumes one token
            expect_status(limited, '/settings', 200, {'action': 'get'})
            expect_status(limited, '/settings', 429, {'action': 'get'})
        finally:
            limited.process.kill(); limited.process.wait(10); limited.close()
        report['management_origin_and_rate_policy'] = True
        server.process.kill(); server.process.wait(10)
        path = server.state/'settings.json'
        path.write_bytes(b'{"BitTorr":')
        restart_after_crash(server)
        recovered = state(server)
        if recovered['saved']['CacheSize'] != 64*MIB or recovered['recovery']['source'] != 'last_known_good':
            raise AssertionError('Corrupt settings lost last-known-good configuration')
        if path.read_bytes() != b'{"BitTorr":':
            raise AssertionError('Startup destroyed corrupt source')
        repaired = copy.deepcopy(recovered['saved']); repaired['Flow']['ManagementRateLimit'] = 0
        with server.request('/settings', {'action': 'set', 'sets': repaired}, headers={'Authorization': server.authorization}, timeout=45):
            pass
        if not list(server.state.glob('flow-corrupt-settings-*.json')) or not json.loads(path.read_bytes()):
            raise AssertionError('Explicit repair did not preserve original')
        report['settings_corruption_preserved_and_repaired'] = True
        report['passed'] = True
    except Exception as error:
        report.update(passed=False, error=str(error))
        raise
    finally:
        server.close()
        (output/'report.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--executable', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(run(args.executable, args.output), indent=2))
